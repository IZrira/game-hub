// 2. 버전 -> 희귀도(5성~3성) -> 이름순으로 정렬된 최종 배열
export const SORTED_LIGHTCONE_DATA = [...LIGHTCONE_DATA].map(lc => ({
  ...lc,
  gameId: lc.gameId || 'hsr' as const
})).sort((a, b) => {
  // 맵에 버전 명시가 안 된 광추는 1.0으로 할당
  const versionA = LIGHTCONE_VERSION_MAP[a.name] || 1.0;
  const versionB = LIGHTCONE_VERSION_MAP[b.name] || 1.0;
  
  // [1순위] 버전 내림차순 (최신 버전이 먼저)
  if (versionA !== versionB) {
    return versionB - versionA;
  }
  
  // [2순위] 버전이 같다면 등급(rarity) 내림차순 (5성 -> 4성 -> 3성)
  if (a.rarity !== b.rarity) {
    return b.rarity - a.rarity;
  }
  
  // [3순위] 버전과 등급까지 같다면 이름 가나다순 정렬
  return a.name.localeCompare(b.name); 
});
